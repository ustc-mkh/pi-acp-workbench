/** Direct domain-to-webview contract; no ACP facade or compatibility wire patches. */
import {
  array,
  boolean,
  checked,
  literal,
  object,
  optional,
  nullable,
  string,
  record,
  tagged,
  uint,
  oneOf,
  type Infer,
  type Schema,
} from './workbench-schema';
import {
  clientCommand,
  harness,
  managementQuery,
  imageRef,
  operationId,
  sessionId,
  sessionSummary,
  sessionView,
  entryHeader,
  entryId,
  toolHeader,
  toolCursor,
  turnId,
  historyCursor,
  listCursor,
  sessionFilter,
  historyClearReport,
  contentRef,
  contentId,
  contentSlice,
  imageAsset,
  typedPrompt,
  turnDiff,
  undoReport,
  managementData,
} from './workbench-protocol';

// Only user-originated commands; no internal event/ACP request or caller-selected operation ID.
export const uiCommand = tagged('type', {
  open_link: object({ type: literal('open_link'), url: string }),
  login: object({ type: literal('login') }),
  copy_message: object({ type: literal('copy_message'), session: sessionId, entry: entryId }),
  copy_text: object({ type: literal('copy_text'), text: string }),
  configure_telegram: object({ type: literal('configure_telegram') }),
  read_management: object({
    type: literal('read_management'),
    query: managementQuery,
    request_id: uint,
    refresh_models: optional(boolean),
  }),
  attach_files: object({ type: literal('attach_files'), session: sessionId }),
  export: object({ type: literal('export'), session: sessionId }),
  recover_operations: object({ type: literal('recover_operations') }),
  refresh_names: object({ type: literal('refresh_names') }),
  ready: object({ type: literal('ready'), harness: optional(harness) }),
  set_harness: object({ type: literal('set_harness'), harness }),
  stop_tracking_unknown: object({
    type: literal('stop_tracking_unknown'),
    operations: checked(array(operationId), (ids) => ids.length <= 64),
  }),
  refresh: object({
    type: literal('refresh'),
    cursor: optional(listCursor),
    filter: optional(sessionFilter),
  }),
  prepare_history_clear: object({ type: literal('prepare_history_clear'), filter: sessionFilter }),
  clear_history_batch: object({ type: literal('clear_history_batch'), job: operationId }),
  create: object({ type: literal('create'), command: clientCommand }),
  select: object({ type: literal('select'), session: sessionId }),
  remove_session: object({ type: literal('remove_session'), session: sessionId }),
  release_session: object({
    type: literal('release_session'),
    session: sessionId,
    confirmed: optional(boolean),
  }),
  clear_selection: object({ type: literal('clear_selection') }),
  execute: object({
    type: literal('execute'),
    session: sessionId,
    command: clientCommand,
    generation: optional(uint),
  }),
  cancel_fork: object({ type: literal('cancel_fork'), operation: operationId }),
  open_turn_diff: object({
    type: literal('open_turn_diff'),
    session: sessionId,
    turn: turnId,
    file: optional(uint),
  }),
  read_turn_diff: object({
    type: literal('read_turn_diff'),
    automatic: optional(boolean),
    session: sessionId,
    turn: turnId,
    offset: optional(uint),
  }),
  read_turn_diff_content: object({
    type: literal('read_turn_diff_content'),
    session: sessionId,
    turn: turnId,
    file: uint,
    after: boolean,
    offset: uint,
  }),
  read_tools: object({
    type: literal('read_tools'),
    session: sessionId,
    turn: turnId,
    cursor: optional(toolCursor),
  }),
  read_content: object({
    type: literal('read_content'),
    session: sessionId,
    ref: contentRef,
    offset: uint,
    request_id: optional(uint),
  }),
  earlier: object({ type: literal('earlier'), session: sessionId }),
  visible_history_text: object({
    type: literal('visible_history_text'),
    session: sessionId,
    ids: checked(array(contentId), (ids) => ids.length <= 128),
  }),
  latest: object({ type: literal('latest'), session: sessionId }),
  read_image: object({
    type: literal('read_image'),
    session: sessionId,
    image: imageRef,
    request_id: optional(uint),
  }),
});
export type UiCommand = Infer<typeof uiCommand>;
// Shared output validation keeps the browser from trusting partial/old extension state.
export const uiOperation = object({
  operation: operationId,
  method: string,
  session: optional(string),
  status: oneOf('pending', 'completed', 'failed', 'uncertain', 'untracked'),
  code: optional(string),
  error: optional(string),
  historyClear: optional(historyClearReport),
});
const readonlyArray = <T>(item: Schema<T>): Schema<readonly T[]> => array(item);
export const uiState = object({
  sessions: array(sessionSummary),
  sessionsCursor: optional(listCursor),
  selected: optional(string),
  preparing: optional(string),
  view: optional(
    object({
      status: oneOf('syncing', 'ready', 'stale', 'removed', 'disconnected'),
      view: optional(sessionView),
      entries: readonlyArray(entryHeader),
      resolvedText: optional(record(string)),
      tools: readonlyArray(toolHeader),
      emptyToolTurns: optional(readonlyArray(turnId)),
      toolCursor: optional(toolCursor),
      earlier: optional(historyCursor),
      historical: boolean,
      historyTruncated: optional(boolean),
      loadingEarlier: optional(boolean),
      earlierLoaded: optional(uint),
      earlierError: optional(string),
      error: optional(string),
    }),
  ),
  operations: array(uiOperation),
  error: optional(string),
  workspace: optional(string),
  trusted: boolean,
});
export const uiStateMessage = object({ type: literal('state'), sequence: uint, state: uiState });

const attachment = object({ id: string, name: string, text: string });
/** One runtime contract for every host-to-webview message. */
export const uiMessage = tagged('type', {
  state: uiStateMessage,
  management: object({
    type: literal('management'),
    request_id: uint,
    data: managementData,
    warning: optional(string),
  }),
  management_error: object({ type: literal('management_error'), request_id: uint, error: string }),
  prompt_submitted: object({
    type: literal('prompt_submitted'),
    session: string,
    operation: operationId,
    generation: optional(uint),
  }),
  prompt_accepted: object({
    type: literal('prompt_accepted'),
    session: string,
    operation: operationId,
    prompt: typedPrompt,
    generation: optional(uint),
    pi_after_seq: optional(uint),
    revision: optional(uint),
  }),
  attachments: object({ type: literal('attachments'), session: string, files: array(attachment) }),
  selection_context: object({ type: literal('selection_context'), file: attachment }),
  draft: object({ type: literal('draft'), text: checked(string, (s) => s.length <= 200000) }),
  turn_diff: object({
    type: literal('turn_diff'),
    session: string,
    turn: string,
    offset: optional(uint),
    diff: turnDiff,
  }),
  turn_diff_error: object({
    type: literal('turn_diff_error'),
    session: string,
    turn: string,
    error: string,
  }),
  turn_diff_content: object({
    type: literal('turn_diff_content'),
    session: string,
    turn: string,
    file: uint,
    after: boolean,
    offset: uint,
    bytes: string,
    total_bytes: uint,
    next_offset: optional(nullable(uint)),
  }),
  undo_result: object({
    type: literal('undo_result'),
    session: string,
    turn: string,
    report: undoReport,
  }),
  image: object({
    type: literal('image'),
    session: string,
    request_id: optional(uint),
    asset: imageAsset,
  }),
  image_error: object({
    type: literal('image_error'),
    session: string,
    request_id: optional(uint),
    image: string,
    error: string,
  }),
  content: object({
    type: literal('content'),
    session: string,
    request_id: optional(uint),
    ref: contentRef,
    offset: uint,
    slice: contentSlice,
  }),
  content_error: object({
    type: literal('content_error'),
    session: string,
    request_id: optional(uint),
    ref: contentRef,
    offset: uint,
    error: string,
  }),
});
export type WorkbenchUiMessage = Infer<typeof uiMessage>;

export type UiOperation = Infer<typeof uiOperation>;
export type WorkbenchUiState = Infer<typeof uiState>;
